import '../models/chapter.dart';

/// Заглушка содержимого книги.
List<Chapter> mockChaptersFor(String editionId) {
  const titles = [
    'Часть первая. Глава 1',
    'Часть первая. Глава 2',
    'Часть первая. Глава 3',
    'Часть вторая. Глава 1',
    'Часть вторая. Глава 2',
    'Часть вторая. Глава 3',
    'Эпилог',
  ];

  const _paragraphs = [
    'В начале июля, в чрезвычайно жаркое время, под вечер, один молодой '
        'человек вышел из своей каморки, которую нанимал от жильцов в '
        'С-м переулке, на улицу и медленно, как бы в нерешимости, отправился '
        'к К-ну мосту.',
    'Он благополучно избегнул встречи с своею хозяйкой на лестнице. Каморка '
        'его приходилась под самою кровлей высокого пятиэтажного дома и '
        'походила более на шкаф, чем на квартиру.',
    'Это была крошечная клетушка, шагов в шесть длиной, имевшая самый '
        'жалкий вид с своими жёлтенькими, пыльными и всюду отставшими от '
        'стены обоями, и до того низкая, что чуть-чуть высокому человеку '
        'становилось в ней и страшно.',
    'Но он до того привык к своему углу, что уже не тяготился им. Он '
        'совсем прекратил ежедневные свои дела и не хотел заниматься.',
    'Впрочем, ему было решительно всё равно, куда ни идти. Идя к К-ну '
        'мосту, он задумался обо всём этом. По временам он как будто '
        'начинал говорить сам с собою.',
    '«Хочу я этакое дело сделать и боюсь пустяков! — подумал он с '
        'странною усмешкой. — Ну, да ведь дела, а не пустяков боятся...»',
  ];

  return List.generate(titles.length, (i) {
    return Chapter(
      title: titles[i],
      paragraphs: List.generate(10, (p) {
        final src = _paragraphs[(i * 10 + p) % _paragraphs.length];
        return '$src\n\n(Заглушка: $editionId, глава ${i + 1}, абзац ${p + 1}.)';
      }),
    );
  });
}